#!/usr/bin/env python3
"""Writes android/launcher/src/main/java/sa/urtv/home/setup/SetupLists.java from optimize/lists: the lists the setup screen on the TV uses are the
very ones `optimize/disable.sh` and `optimize/restore.sh` use from a computer (tests/setup_lists_test.py fails when the committed file drifts).
And the community lists (optimize/lists/community/, CleanYourTV, MIT) as one small asset of the app, android/launcher/src/main/assets/setup/community.txt,
read by CommunityMatch.java: each package once (`P <package>`, numbered from 0), each list on one line (`L name|brands|models|devices|<numbers in base 36>`,
the header values as optimize/community.py reads them), the expressions of community-ask.txt (`A …`) and the TCL packages our own lists know (`K …`).

    python3 optimize/gen_setup_lists.py            rewrite both files
    python3 optimize/gen_setup_lists.py --check    exit 1 when either is not what the lists say
"""
import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "android/launcher/src/main/java/sa/urtv/home/setup/SetupLists.java"
ASSET = ROOT / "android/launcher/src/main/assets/setup/community.txt"
LISTS = (("SAFE", "tcl-safe.txt", "the safe list: telemetry, ads, promos and helpers nobody opens (optimize/lists/tcl-safe.txt)"),
         ("KEEP", "keep.txt", "never turned off: features people use (optimize/lists/keep.txt)"),
         ("CORE", "core.txt", "never turned off: Android's own core, regular expressions matched against the whole name (optimize/lists/core.txt)"),
         ("HOME_HELPERS", "home-replaced.txt", "the stock home's helpers, turned off after our home is confirmed and back on with the stock home (optimize/lists/home-replaced.txt)"))


def words(path):
    out = []
    for line in path.read_text(encoding="utf-8").splitlines():
        s = line.strip()
        if s and not s.startswith("#"):
            out.append(s.split()[0])
    return out


def render():
    lines = ["package sa.urtv.home.setup;", "",
             "/** GENERATED by optimize/gen_setup_lists.py from optimize/lists: do not edit. tests/setup_lists_test.py fails when it drifts. */",
             "final class SetupLists {", "    private SetupLists() { }", ""]
    for name, file, doc in LISTS:
        lines.append(f"    /** {doc} */")
        lines.append(f"    static final String[] {name} = {{")
        for w in words(ROOT / "optimize/lists" / file):
            assert all(c.isalnum() or c in "._-\\()|*+?[]^$" for c in w), w
            lines.append('        "' + w.replace("\\", "\\\\") + '",')
        lines.append("    };")
        lines.append("")
    lines.append("}")
    return "\n".join(lines) + "\n"


def b36(n):
    digits = "0123456789abcdefghijklmnopqrstuvwxyz"
    out = ""
    while True:
        n, r = divmod(n, 36)
        out = digits[r] + out
        if n == 0:
            return out


def community():
    spec = importlib.util.spec_from_file_location("community", ROOT / "optimize/community.py")
    com = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(com)
    lists = []
    for meta in com.all_metas():
        lists.append((Path(meta["path"]).stem, meta, com.load(meta["path"])[1]))
    index, pkgs = {}, []
    for _, _, ps in lists:
        for p in ps:
            if p not in index:
                index[p] = len(pkgs)
                pkgs.append(p)
    lines = ["# GENERATED by optimize/gen_setup_lists.py from optimize/lists/community (CleanYourTV, MIT: see LICENSE-CleanYourTV.txt there) and community-ask.txt: do not edit."]
    lines += [f"P {p}" for p in pkgs]
    for name, meta, ps in lists:
        f = [name, " ".join(sorted(meta["brands"])), " ".join(sorted(meta["models"])), " ".join(sorted(meta["devices"])), " ".join(b36(index[p]) for p in ps)]
        assert not any("|" in x for x in f), name
        lines.append("L " + "|".join(f))
    lines += ["A " + a for a in words_raw(ROOT / "optimize/lists/community-ask.txt")]
    known = sorted({w for f in ("tcl-safe.txt", "tcl-optional.txt") for w in words(ROOT / "optimize/lists" / f) if w.startswith("com.tcl.")})
    lines += ["K " + k for k in known]
    return "\n".join(lines) + "\n"


def words_raw(path):   # community.sh's `grep -E '^[^#[:space:]]'`: the whole line, a regular expression
    return [l for l in path.read_text(encoding="utf-8").splitlines() if l and not l[0].isspace() and l[0] != "#"]


if __name__ == "__main__":
    text, asset = render(), community()
    if sys.argv[1:] == ["--check"]:
        sys.exit(0 if OUT.exists() and OUT.read_text(encoding="utf-8") == text and ASSET.exists() and ASSET.read_text(encoding="utf-8") == asset else 1)
    OUT.write_text(text, encoding="utf-8")
    ASSET.parent.mkdir(parents=True, exist_ok=True)
    ASSET.write_text(asset, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} and {ASSET.relative_to(ROOT)} ({len(asset.encode())} bytes)")
