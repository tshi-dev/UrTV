    private static volatile WordMatch match;

    /** the text in «اللغة»: itself with Arabic; with English its entry, its parts' entries, or itself (a name, data) */
    static String of(String s) {
        if (!S.en() || s == null) return s;
        WordMatch m = match;
        if (m == null) match = m = new WordMatch(new WordMatch.Table() {
            @Override public String en(String ar, Object... args) {
                if (S.tv(ar).equals(ar)) return null;   // no entry (or one that keeps the Arabic)
                return S.tv(ar, args);
            }
            @Override public String name(String ar) { return Places.name(ar); }
        }, PATTERNS);
        return m.of(s);
    }

    /** a saved city ({name, latitude, longitude}) as shown: its name, or with English the built-in city's English name (Places) */
    static String city(String[] saved) {
        if (!S.en()) return saved[0];
        String en = Places.city(saved[0], saved[1], saved[2]);
        return en != null ? en : saved[0];
    }

    /** a built-in city's row in a list: «الخرطوم · Khartoum» (Cities.display), or with English its English name alone */
    static String display(String[] row) {
        if (!S.en()) return Cities.display(row);
        String en = Places.city(row);
        return en != null ? en : Cities.display(row);
    }

    /** of() for each one, a new array (the dialogs' lists) */
    static CharSequence[] of(CharSequence[] items) {
        if (!S.en() || items == null) return items;
        CharSequence[] out = new CharSequence[items.length];
        for (int i = 0; i < items.length; i++) out[i] = items[i] == null ? null : of(items[i].toString());
        return out;
    }
